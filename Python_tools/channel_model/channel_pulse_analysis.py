def parse_eng(s: str) -> float:
    suffixes = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3,
                "k": 1e3, "meg": 1e6, "g": 1e9, "t": 1e12}
    s = str(s).strip()
    for suf, mult in sorted(suffixes.items(), key=lambda x: -len(x[0])):
        if s.lower().endswith(suf):
            return float(s[:-len(suf)]) * mult
    return float(s)


# ----------------------------------------------------------------------
# Reading parameters from the .sp generated by channel_model_generator.py
# ----------------------------------------------------------------------

def parse_channel_sp(sp_path: str):
    with open(sp_path) as f:
        text = f.read()

    # Accepts the current English header ("Fitted loss: ... dB at DC", "xN stages") and
    # the previous Spanish one ("Pérdida ajustada: ... dB en DC", "xN etapas"), so .sp
    # files generated before the translation can still be analyzed.
    m_fp = re.search(r"fp1=([\d.]+)\s*GHz\s+fp2=([\d.]+)\s*GHz.*?x(\d+)\s*(?:stages|etapas)", text)
    m_dc = re.search(r"(?:Fitted loss|Pérdida ajustada):\s*([\d.\-]+)\s*dB (?:at|en) DC", text)

    if not m_fp or not m_dc:
        raise ValueError(
            f"Could not read fp1/fp2/n_stages/loss_dc from the header of '{sp_path}'. "
            f"Pass them explicitly with --fp1/--fp2/--loss-dc/--n-stages."
        )

    fp1 = float(m_fp.group(1)) * 1e9
    fp2 = float(m_fp.group(2)) * 1e9
    n_stages = int(m_fp.group(3))
    loss_dc_db = float(m_dc.group(1))
    return fp1, fp2, loss_dc_db, n_stages


# ----------------------------------------------------------------------
# Analytic transfer function of the channel
# ----------------------------------------------------------------------

def build_channel_tf(fp1: float, fp2: float, loss_dc_db: float, n_stages: int) -> signal.TransferFunction:
    """H_stage(s) = (1+s/wp2)/(1+s/wp1), cascaded n_stages times, with the
    DC pad as a scalar gain. It matches exactly the SPICE topology generated
    by channel_model_generator.py (see the derivation, verified numerically
    against the loss formula)."""
    wp1, wp2 = 2 * np.pi * fp1, 2 * np.pi * fp2
    num_stage = [1 / wp2, 1]
    den_stage = [1 / wp1, 1]

    num_total = np.array([1.0])
    den_total = np.array([1.0])
    for _ in range(n_stages):
        num_total = np.polymul(num_total, num_stage)
        den_total = np.polymul(den_total, den_stage)

    pad_gain = 10 ** (-loss_dc_db / 20)
    num_total = num_total * pad_gain
    return signal.TransferFunction(num_total, den_total)


def build_ctle_tf(gmN: float, RL: float, CLtot: float, Rs: float, Cs: float, gdsN: float = 0.0):
    """
    Differential-pair CTLE with resistive+capacitive degeneration
    (Rs || Cs at the tail, RL || CLtot at the load), with gdsN included
    (output conductance of the transistor, in parallel with RL).

    H(s) = [n1*s + n0] / [d2*s^2 + d1*s + d0], with RL replaced by
    RL_eff = RL/(1+gdsN*RL) in all the coefficients -- verified
    algebraically (sympy) that wp1 and wp2 remain EXACT roots of the
    denominator with this substitution:
        wz  = 1/(Rs*Cs)                              (unchanged)
        wp1 = (1+gmN*Rs/2)/(Rs*Cs)                    (unchanged, does not depend on RL/gdsN)
        wp2 = (1+RL*gdsN)/(RL*CLtot)                  (previously 1/(RL*CLtot); gdsN pushes it to a higher frequency)

    Returns (tf, info) where info is a dict with wz, wp1, wp2 (in rad/s
    and Hz), dc_gain, ac_gain, boost_db, and which of wp1/wp2 is larger.
    """
    RL_eff = RL / (1 + gdsN * RL)

    n1 = 2 * Cs * gmN * RL_eff * Rs
    n0 = 2 * gmN * RL_eff
    d2 = 2 * CLtot * Cs * RL_eff * Rs
    d1 = 2 * CLtot * RL_eff + 2 * Cs * Rs + CLtot * gmN * RL_eff * Rs
    d0 = 2 + gmN * Rs

    tf = signal.TransferFunction([n1, n0], [d2, d1, d0])

    wz = 1.0 / (Rs * Cs)
    wp1 = (1.0 + gmN * Rs / 2.0) / (Rs * Cs)
    wp2 = (1.0 + RL * gdsN) / (RL * CLtot)

    dc_gain = n0 / d0
    ac_gain = dc_gain * (wp1 / wz)
    boost_db = 20 * np.log10(wp1 / wz)

    info = {
        "wz": wz, "wp1": wp1, "wp2": wp2,
        "fz": wz / (2 * np.pi), "fp1": wp1 / (2 * np.pi), "fp2": wp2 / (2 * np.pi),
        "dc_gain": dc_gain, "ac_gain": ac_gain, "boost_db": boost_db,
        "wp2_gt_wp1": wp2 > wp1,
    }
    return tf, info


def cascade_tf(tf1: signal.TransferFunction, tf2: signal.TransferFunction) -> signal.TransferFunction:
    """Combines two transfer functions in cascade (exact polynomial
    multiplication) -- valid because both are LTI systems, with no need for
    time-domain convolution or any approximation."""
    num = np.polymul(tf1.num, tf2.num)
    den = np.polymul(tf1.den, tf2.den)
    return signal.TransferFunction(num, den)


