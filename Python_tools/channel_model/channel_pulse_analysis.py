def build_ctle_tf_from_gains(dc_gain_db: float, boost_db: float, f_nyquist: float, f_p2: float,
                              pole1_frac: float = 1.0):
    """
    Third way of building the CTLE: directly from DC gain, Boost (= AC
    gain - DC gain, in dB), the Nyquist frequency, and fp2 (the output
    pole).

    FIXED: the first version placed the ZERO at Nyquist -- that is wrong.
    According to Razavi ("The Design of an Equalizer, Part One", IEEE
    SSCS Magazine, Fall 2021, section "CTLE Design" and Fig. 4b/6/Eq. 8),
    the correct criterion is the opposite: the POLE wp1 must lie BELOW
    Nyquist (so that the curve is already flat -- on the ACgain plateau --
    when it reaches Nyquist), and the zero wz lies even lower. wp2 (the
    output pole) lies AFTER Nyquist.

    NOTE: DCgain + ACgain + Nyquist are NOT enough to determine wz and wp1
    separately -- Boost = ACgain/DCgain = wp1/wz is a SINGLE equation with
    TWO unknowns (verified with sympy). One of the two must be anchored to
    Nyquist; following the article, wp1 is anchored:
        wp1 = pole1_frac * 2*pi*f_nyquist / boost_ratio
        wz  = wp1 / boost_ratio
        wp2 = 2*pi*f_p2                     (given directly)
    With pole1_frac=1.0 (default) this coincides exactly with
    wp1 = 2*pi*fnyq/peaking_linear -- the formula you were already using.
    For a boost of 2-3x, this puts fp1 between ~2 and 3 times below
    fNyq, consistent with Eq. 8 of the article.

    H(s) = DCgain*(1+s/wz) / [(1+s/wp1)*(1+s/wp2)]
    (same structure as the transistor model, verified algebraically to be
    the exact form when gdsN=0).
    """
    dc_gain = 10 ** (dc_gain_db / 20)
    boost_ratio = 10 ** (boost_db / 20)  # = wp1/wz = ACgain/DCgain
    ac_gain = dc_gain * boost_ratio

    wp1 = pole1_frac * 2 * np.pi * f_nyquist / boost_ratio
    wz = wp1 / boost_ratio
    wp2 = 2 * np.pi * f_p2

    num = [dc_gain / wz, dc_gain]
    den = np.polymul([1 / wp1, 1], [1 / wp2, 1])
    tf = signal.TransferFunction(num, den)

    info = {
        "wz": wz, "wp1": wp1, "wp2": wp2,
        "fz": wz / (2 * np.pi), "fp1": wp1 / (2 * np.pi), "fp2": wp2 / (2 * np.pi),
        "dc_gain": dc_gain, "ac_gain": ac_gain, "boost_db": boost_db,
        "wp2_gt_wp1": wp2 > wp1,
    }
    return tf, info


def estimate_transistor_params(dc_gain: float, ac_gain: float, wz: float, wp1: float, wp2: float,
                                gmN_assumed: float):
    """
    Estimates Rs, Cs, RL, CLtot of the transistor circuit from
    (dc_gain, ac_gain, wz, wp1, wp2) -- the same 4 numbers that come out of
    the 'gains' mode -- ASSUMING a value of gmN.

    Why gmN has to be assumed: the system has 4 equations (wz, wp1, DCgain,
    wp2) but 5 unknowns (gmN, RL, CLtot, Rs, Cs) -- ONE degree of freedom
    is left unfixed. gmN is the natural choice, because in a real design
    flow it is normally already determined by the bias-current budget and
    the transistor overdrive (gm ~ 2*Itail/Vov), before the resistors are
    chosen.

    Formulas (verified with sympy, they reconstruct wp1 and DCgain exactly):
        Rs    = 2*(wp1-wz) / (gmN*wz)
        Cs    = 1 / (wz*Rs) = gmN / (2*(wp1-wz))
        RL    = ac_gain / gmN
        CLtot = 1 / (wp2*RL) = gmN / (ac_gain*wp2)

    NOTE: this assumes gdsN=0 (gdsN cannot be solved from these 4 numbers
    without another independent equation -- in practice gdsN is obtained
    from the characterization of the transistor at its bias point, not from
    this calculation).
    """
    Rs = 2 * (wp1 - wz) / (gmN_assumed * wz)
    Cs = 1.0 / (wz * Rs)
    RL = ac_gain / gmN_assumed
    CLtot = 1.0 / (wp2 * RL)
    return {"Rs": Rs, "Cs": Cs, "RL": RL, "CLtot": CLtot, "gmN_assumed": gmN_assumed}


