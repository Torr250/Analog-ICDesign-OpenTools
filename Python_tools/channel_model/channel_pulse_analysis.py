#!/usr/bin/env python3
"""
channel_pulse_analysis.py

Analyzes the channel_model.sp generated by channel_model_generator.py using
the pulse response, the AC response, and the channel-coefficients method for
the Worst Case Eye Height (WC eye height) -- adapted from the user's
serdes_functions.py code, but WITHOUT depending on serdespy or on impulse
response files (.mat): since the EXACT analytic transfer function of the
shelving filter is known (a cascade of pole-zero sections), the pulse
response can be computed directly with scipy.signal, with no need to
simulate in ngspice or to use FFTs/windowing.

CHANNEL-COEFFICIENTS METHOD (same as serdes_functions.py):
  - The pulse response is computed (a rectangular pulse 1 UI wide through
    the channel).
  - That response is sampled at multiples of the UI around the peak (the
    main cursor) -- this gives the "channel coefficients":
    n precursors, the main cursor, n postcursors.
  - Worst Case Eye Height: all the NEGATIVE coefficients (constructive for
    the "1" symbol, since they subtract from the "0") and all the POSITIVE
    ones (constructive for the "0" symbol) are summed separately, and
    combined with the main cursor to estimate the vertical opening for the
    worst possible bit pattern. Positive = open eye, negative = closed eye.

Usage:
    python3 channel_pulse_analysis.py channel_model/channel_model.sp --datarate 1e9
    python3 channel_pulse_analysis.py channel_model/channel_model.sp --datarate 1e9 \
        --n-precursors 10 --n-postcursors 100

If fp1/fp2/loss-dc/n-stages are not passed explicitly, they are read
automatically from the comment header of the .sp file (the one generated by
channel_model_generator.py).

Requires: numpy, scipy, matplotlib
"""

