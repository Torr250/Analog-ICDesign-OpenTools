def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sp_path", help="Path to the channel_model.sp generated by channel_model_generator.py")
    parser.add_argument("--datarate", type=str, required=True, help="NRZ data rate, e.g. '1e9' (1Gbps)")
    parser.add_argument("--fp1", type=str, default=None, help="Manual override of fp1 (if it cannot be read from the .sp)")
    parser.add_argument("--fp2", type=str, default=None, help="Manual override of fp2")
    parser.add_argument("--loss-dc", type=float, default=None, help="Manual override of loss_dc (dB)")
    parser.add_argument("--n-stages", type=int, default=None, help="Manual override of n_stages")
    parser.add_argument("--n-precursors", type=int, default=10, help="Number of precursors to consider (default: 10)")
    parser.add_argument("--n-postcursors", type=int, default=100, help="Number of postcursors to consider (default: 100)")
    parser.add_argument("--ffe-pre", type=float, nargs="*", default=[],
                         help="Magnitudes (positive, 0 to 0.4) of the pre-cursor FFE taps, from the farthest to the "
                              "closest to the main cursor. E.g.: --ffe-pre 0.05 0.15 for 2 precursors.")
    parser.add_argument("--ffe-post", type=float, nargs="*", default=[],
                         help="Magnitudes (positive, 0 to 0.4) of the post-cursor FFE taps, from the closest to the "
                              "farthest. E.g.: --ffe-post 0.25 for 1 postcursor.")
    parser.add_argument("--outdir", default="pulse_analysis", help="Output directory")
    parser.add_argument("--plot-worst-case-eye", action="store_true",
                         help="Generates the deterministic worst-case eye diagram (the exact bit sequence "
                              "that produces the computed WC eye height)")
    parser.add_argument("--overlay-eye-npz", type=str, default=None,
                         help="Path to an eye_folded_data.npz generated by eye_diagram.py (real PRBS via "
                              "ngspice), to overlay it in the background as a visual reference of the typical case")
    parser.add_argument("--vdd", type=float, default=None,
                         help="Real VDD of the circuit (V). If passed, rescales the traces from bipolar +-1 to "
                              "unipolar 0..VDD -- needed so that --overlay-eye-npz (ngspice data, "
                              "in real Volts) is overlaid on the same scale.")
    parser.add_argument("--ctle-gmn", type=float, default=None, help="CTLE: gm of the NMOS transistor (S)")
    parser.add_argument("--ctle-rl", type=float, default=None, help="CTLE: load resistance RL (Ohm)")
    parser.add_argument("--ctle-cltot", type=float, default=None, help="CTLE: total load capacitance CLtot (F)")
    parser.add_argument("--ctle-rs", type=float, default=None, help="CTLE: degeneration resistance Rs (Ohm)")
    parser.add_argument("--ctle-cs", type=float, default=None, help="CTLE: degeneration capacitance Cs (F)")
    parser.add_argument("--ctle-gdsn", type=float, default=0.0,
                         help="CTLE: NMOS output conductance gdsN (S). Default: 0 (ideal, no gdsN)")
    parser.add_argument("--ctle-model", choices=["analytic", "measured", "gains"], default="analytic",
                         help="Source of the CTLE response: 'analytic' (2 poles+1 zero, parameters "
                              "--ctle-gmn/rl/cltot/rs/cs/gdsn), 'measured' (external CSV), or 'gains' "
                              "(DC gain + Boost + fp2, with wp1 below Nyquist). Default: analytic.")
    parser.add_argument("--ctle-response-csv", type=str, default=None,
                         help="Path to the CSV (freq_hz,mag_db,phase_deg) with the measured/simulated response of "
                              "the CTLE. Required if --ctle-model measured.")
    parser.add_argument("--ctle-dcgain-db", type=float, default=None,
                         help="CTLE ('gains' mode): DC gain, in dB")
    parser.add_argument("--ctle-boost-db", type=float, default=None,
                         help="CTLE ('gains' mode): Boost = AC gain - DC gain, in dB")
    parser.add_argument("--ctle-fp2", type=float, default=None,
                         help="CTLE ('gains' mode): frequency of the output pole fp2, in Hz")
    parser.add_argument("--ctle-pole1-frac", type=float, default=1.0,
                         help="CTLE ('gains' mode): wp1 is placed at pole1_frac * (2*pi*f_nyquist/boost_ratio). "
                              "Default: 1.0 (coincides with the formula wp1=2*pi*fnyq/boost_ratio).")
    parser.add_argument("--ctle-estimate-gmn", type=float, default=None,
                         help="If passed (together with --ctle-model gains), estimates Rs/Cs/RL/CLtot of the "
                              "transistor circuit assuming this value of gmN (S). See print_estimated_params "
                              "for the explanation of why gmN has to be assumed.")
    args = parser.parse_args()


    os.makedirs(args.outdir, exist_ok=True)
    datarate = parse_eng(args.datarate)
    ui = 1.0 / datarate

    if None in (args.fp1, args.fp2, args.loss_dc, args.n_stages):
        try:
            fp1_auto, fp2_auto, loss_dc_auto, n_stages_auto = parse_channel_sp(args.sp_path)
        except ValueError as exc:
            print(f"Error: {exc}", file=sys.stderr)
            sys.exit(1)
        fp1 = parse_eng(args.fp1) if args.fp1 is not None else fp1_auto
        fp2 = parse_eng(args.fp2) if args.fp2 is not None else fp2_auto
        loss_dc_db = args.loss_dc if args.loss_dc is not None else loss_dc_auto
        n_stages = args.n_stages if args.n_stages is not None else n_stages_auto
    else:
        fp1, fp2 = parse_eng(args.fp1), parse_eng(args.fp2)
        loss_dc_db, n_stages = args.loss_dc, args.n_stages

    print(f"Channel: fp1={fp1/1e9:.4f}GHz  fp2={fp2/1e9:.4f}GHz  loss_dc={loss_dc_db:.3f}dB  "
          f"n_stages={n_stages}  UI={ui*1e12:.2f}ps (datarate={datarate:.3e})\n")

    tf = build_channel_tf(fp1, fp2, loss_dc_db, n_stages)

    # --- AC response (of the channel alone; the FFE cannot be seen here
    # without also converting it to a transfer function -- this is left for
    # when we add the CTLE, which is more natural to view in AC) ---
    plot_ac_response(tf, fp2 * 3, os.path.join(args.outdir, "ac_response.png"))

    # --- pulse response of the channel alone ---
    dt = ui / 200  # 200 samples per UI, sufficient resolution
    n_ui_total = args.n_precursors + args.n_postcursors + 20
    t, pulse = compute_pulse_response(tf, ui, dt, n_ui_total)
    plot_pulse_response(t, pulse, ui, os.path.join(args.outdir, "pulse_response.png"))
    samples_per_symbol = int(round(ui / dt))

    def report(pulse_response, label, fname_suffix):
        coeffs = channel_coefficients(pulse_response, samples_per_symbol, args.n_precursors, args.n_postcursors)
        plot_channel_coefficients(coeffs, args.n_precursors,
                                   os.path.join(args.outdir, f"channel_coefficients{fname_suffix}.png"))
        wceh = wc_eye_height(pulse_response, samples_per_symbol, args.n_precursors, args.n_postcursors)
        print(f"--- {label} ---")
        print(f"Main cursor (n=0): {coeffs[args.n_precursors]:.6f}")
        print(f"Sum |precursors|+|postcursors| (total ISI): "
              f"{np.sum(np.abs(coeffs)) - abs(coeffs[args.n_precursors]):.6f}")
        print(f"WORST CASE EYE HEIGHT: {wceh:.6f}  ({'EYE OPEN' if wceh > 0 else 'EYE CLOSED'})\n")

        if args.plot_worst_case_eye:
            plot_worst_case_eye(pulse_response, samples_per_symbol, args.n_precursors, args.n_postcursors,
                                 wceh, os.path.join(args.outdir, f"worst_case_eye{fname_suffix}.png"),
                                 overlay_npz=args.overlay_eye_npz, vdd=args.vdd)
        return wceh

    print("=" * 60)
    print("CHANNEL ONLY (no equalization)")
    print("=" * 60)
    report(pulse, "Channel only", "")

    ffe_given = bool(args.ffe_pre or args.ffe_post)
    ctle_given = (
        (args.ctle_model == "measured" and args.ctle_response_csv is not None) or
        (args.ctle_model == "gains" and
         None not in (args.ctle_dcgain_db, args.ctle_boost_db, args.ctle_fp2)) or
        (args.ctle_model == "analytic" and
         None not in (args.ctle_gmn, args.ctle_rl, args.ctle_cltot, args.ctle_rs, args.ctle_cs))
    )

    ffe_taps = None
    if ffe_given:
        try:
            ffe_taps = build_ffe_taps(args.ffe_pre, args.ffe_post)
        except ValueError as exc:
            print(f"Error: {exc}", file=sys.stderr)
            sys.exit(1)
        print(f"FFE taps applied: {ffe_taps}  (order: [pre...  main  ...post])\n")

    ctle_response_fn, ctle_info, ctle_desc = (None, None, None)
    if ctle_given:
        ctle_response_fn, ctle_info, ctle_desc = get_ctle_response_fn(args, datarate / 2)
        print("=" * 60)
        print(f"CTLE ({ctle_desc})")
        print("=" * 60)
        if ctle_info is not None:
            print_ctle_info(ctle_info)
        else:
            print("(imported response, no analytic poles/zeros to report)\n")

        if args.ctle_model == "gains" and args.ctle_estimate_gmn is not None:
            est = estimate_transistor_params(ctle_info["dc_gain"], ctle_info["ac_gain"],
                                              ctle_info["wz"], ctle_info["wp1"], ctle_info["wp2"],
                                              args.ctle_estimate_gmn)
            print_estimated_params(est)

    # --- combined AC response: Channel, +FFE, +FFE+CTLE (or +CTLE if there is no FFE) ---
    if ffe_given or ctle_given:
        freqs_ac = np.linspace(1e6, fp2 * 3, 2000)
        H_channel = compute_ac_response(tf, freqs_ac)
        curves = {"Channel": H_channel}
        H_running = H_channel

        if ffe_given:
            H_ffe = compute_ffe_response(ffe_taps, len(args.ffe_pre), ui, freqs_ac)
            H_running = H_running * H_ffe
            curves["Channel + FFE"] = H_running

        if ctle_given:
            H_ctle = ctle_response_fn(freqs_ac)
            H_running = H_running * H_ctle
            label = "Channel + FFE + CTLE" if ffe_given else "Channel + CTLE"
            curves[label] = H_running

        plot_combined_ac_response(freqs_ac, curves, datarate / 2,
                                   os.path.join(args.outdir, "ac_response_combined.png"))

    # --- Channel + CTLE (without FFE) in the time domain ---
    pulse_channel_ctle = pulse
    if ctle_given:
        if args.ctle_model == "analytic":
            ctle_tf, _ = build_ctle_tf(args.ctle_gmn, args.ctle_rl, args.ctle_cltot,
                                        args.ctle_rs, args.ctle_cs, args.ctle_gdsn)
            tf_channel_ctle = cascade_tf(tf, ctle_tf)
            t_ctle, pulse_channel_ctle = compute_pulse_response(tf_channel_ctle, ui, dt, n_ui_total)
        elif args.ctle_model == "gains":
            ctle_tf, _ = build_ctle_tf_from_gains(args.ctle_dcgain_db, args.ctle_boost_db,
                                                   datarate / 2, args.ctle_fp2, args.ctle_pole1_frac)
            tf_channel_ctle = cascade_tf(tf, ctle_tf)
            t_ctle, pulse_channel_ctle = compute_pulse_response(tf_channel_ctle, ui, dt, n_ui_total)
        else:
            def combined_fn(freqs):
                return compute_ac_response(tf, freqs) * ctle_response_fn(freqs)
            t_ctle, pulse_channel_ctle = pulse_response_from_freq_response(combined_fn, ui, dt, n_ui_total)

        plot_pulse_response(t_ctle, pulse_channel_ctle, ui,
                             os.path.join(args.outdir, "pulse_response_ctle.png"),
                             label="Pulse response — Channel + CTLE")

        print("=" * 60)
        print("CHANNEL + CTLE")
        print("=" * 60)
        report(pulse_channel_ctle, "Channel + CTLE", "_ctle")

    # --- Channel + FFE (and +CTLE if applicable) in the time domain ---
    if ffe_given:
        pulse_ffe = apply_ffe(pulse, samples_per_symbol, ffe_taps)
        plot_pulse_response(t[:len(pulse_ffe)] if len(t) >= len(pulse_ffe) else
                             np.arange(len(pulse_ffe)) * dt,
                             pulse_ffe, ui, os.path.join(args.outdir, "pulse_response_ffe.png"),
                             label="Pulse response — Channel + FFE")

        print("=" * 60)
        print("CHANNEL + FFE")
        print("=" * 60)
        report(pulse_ffe, "Channel + FFE", "_ffe")

        if ctle_given:
            pulse_ffe_ctle = apply_ffe(pulse_channel_ctle, samples_per_symbol, ffe_taps)
            plot_pulse_response(np.arange(len(pulse_ffe_ctle)) * dt, pulse_ffe_ctle, ui,
                                 os.path.join(args.outdir, "pulse_response_ffe_ctle.png"),
                                 label="Pulse response — Channel + FFE + CTLE")

            print("=" * 60)
            print("CHANNEL + FFE + CTLE")
            print("=" * 60)
            report(pulse_ffe_ctle, "Channel + FFE + CTLE", "_ffe_ctle")

    print("(the WC eye height values are in the same units as the amplitude of the input pulse -- ")
    print(" if your real signal has swing +/-A, multiply the result by A)")


