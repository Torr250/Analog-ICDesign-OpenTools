# ----------------------------------------------------------------------
# FFE (Tx Feed-Forward Equalizer): pre-cursor(s) + main + post-cursor(s)
# ----------------------------------------------------------------------

def build_ffe_taps(pre_taps: list, post_taps: list) -> np.ndarray:
    """
    Builds the FFE coefficient vector from the pre- and post-cursor
    magnitudes (positive, the ones you choose). The main tap is computed by
    NORMALIZATION: main = 1 - sum(|pre|) - sum(|post|), and pre/post are
    applied with a NEGATIVE sign (de-emphasis) -- same convention as
    serdes_functions.py (PCIe-style).

    Order of the returned vector: [-pre_n, ..., -pre_1, main, -post_1, ..., -post_m]
    """
    pre_taps = list(pre_taps)
    post_taps = list(post_taps)

    for tap in pre_taps + post_taps:
        if not (0 <= tap <= 0.4):
            raise ValueError(f"FFE tap out of range [0, 0.4]: {tap}")

    main_tap = 1.0 - sum(pre_taps) - sum(post_taps)
    if main_tap <= 0:
        raise ValueError(
            f"The computed main tap (1 - sum of pre/post) is {main_tap:.4f} <= 0 -- "
            f"the sum of your pre/post-cursor taps is too large."
        )

    taps = [-t for t in reversed(pre_taps)] + [main_tap] + [-t for t in post_taps]
    return np.array(taps)


def apply_ffe(pulse_response: np.ndarray, samples_per_symbol: int, ffe_taps: np.ndarray) -> np.ndarray:
    """
    Applies the FFE by convolving its tap sequence (each one separated by
    1 UI = samples_per_symbol samples) with the channel pulse response --
    exactly equivalent to pre-distorting the input signal with the FFE
    before it goes through the channel (the channel is LTI, so the order
    does not matter), and it is the same operation done by
    serdes_functions.py (fftconvolve(ir, repeated_taps)).

    There is no need to realign the result by hand: channel_coefficients()
    and wc_eye_height() locate the main cursor by searching for the
    maximum, so they work the same on the equalized response.
    """
    taps_upsampled = np.zeros((len(ffe_taps) - 1) * samples_per_symbol + 1)
    taps_upsampled[::samples_per_symbol] = ffe_taps
    return signal.fftconvolve(pulse_response, taps_upsampled, mode="full")


def compute_ffe_response(ffe_taps: np.ndarray, n_pre_taps: int, ui: float, freqs: np.ndarray) -> np.ndarray:
    """
    Frequency response of the FFE: since it is a discrete FIR (each tap
    separated by 1 UI), its response is the DTFT of the coefficients --
    H_FFE(f) = sum_k tap[k] * exp(-j*2*pi*f*k*UI), with k=0 at the main tap
    (positive toward postcursors, negative toward precursors).
    This is what generates the peaking near Nyquist depending on the
    pre/post values you choose -- de-emphasis coefficients (negative
    pre/post) typically boost the high frequencies.
    """
    k = np.arange(len(ffe_taps)) - n_pre_taps
    # exp(-j*2*pi*f*k*UI) for each (freqs x k) combination, summed over k
    phase = -2j * np.pi * np.outer(freqs, k) * ui
    return np.sum(ffe_taps[np.newaxis, :] * np.exp(phase), axis=1)


# ----------------------------------------------------------------------
# CTLE: source of the response -- analytic (2 poles + 1 zero) or measured
# (for example, extracted from an ngspice .AC on the real transistor
# circuit) -- both end up simply being H(f), so they are combined the same
# way regardless of their origin.
# ----------------------------------------------------------------------

def load_measured_response(csv_path: str):
    """
    Loads a MEASURED/SIMULATED frequency response from a CSV with columns:
    freq_hz, mag_db, phase_deg (one header row, in that order). Meant for
    pasting directly the output of an ngspice .AC on the real transistor
    circuit of the CTLE.

    Returns a function freqs -> H(freqs) (complex), by linear interpolation
    of magnitude (dB) and phase (degrees) over the measured grid.

    IMPORTANT: outside the CSV frequency range, the response is taken to
    ZERO (the last value is not held constant) -- otherwise, when using this
    with the FFT-based synthesis (which needs frequencies up to the Nyquist
    of the time grid, typically hundreds of GHz) non-physical high-frequency
    energy would be fabricated, contaminating the resulting pulse response.
    """
    data = np.genfromtxt(csv_path, delimiter=",", skip_header=1)
    freq_meas, mag_db_meas, phase_deg_meas = data[:, 0], data[:, 1], data[:, 2]
    f_min, f_max = freq_meas.min(), freq_meas.max()

    def response_fn(freqs: np.ndarray) -> np.ndarray:
        mag_db = np.interp(freqs, freq_meas, mag_db_meas)
        phase_deg = np.interp(freqs, freq_meas, phase_deg_meas)
        mag = 10 ** (mag_db / 20)
        phase = np.deg2rad(phase_deg)
        H = mag * np.exp(1j * phase)
        H = np.where(freqs > f_max, 0.0, H)
        return H

    return response_fn


def get_ctle_response_fn(args, f_nyquist: float):
    """
    Dispatcher: returns (response_fn, info_or_None, description) according
    to --ctle-model.
      'analytic' uses build_ctle_tf (parameters gmN/RL/CLtot/Rs/Cs/gdsN)
      'measured' loads --ctle-response-csv
      'gains'    uses build_ctle_tf_from_gains (DC gain, Boost, fp2,
                 with wp1 at --ctle-pole1-frac * Nyquist/boost)
    info is the dict of wz/wp1/wp2/etc. if analytic or gains, None if
    measured (it makes no sense to report poles/zeros of a measured curve).
    """
    if args.ctle_model == "measured":
        if not args.ctle_response_csv:
            raise ValueError("--ctle-model measured requires --ctle-response-csv")
        response_fn = load_measured_response(args.ctle_response_csv)
        return response_fn, None, f"measured ({args.ctle_response_csv})"
    elif args.ctle_model == "gains":
        if None in (args.ctle_dcgain_db, args.ctle_boost_db, args.ctle_fp2):
            raise ValueError("--ctle-model gains requires --ctle-dcgain-db, --ctle-boost-db and --ctle-fp2")
        ctle_tf, info = build_ctle_tf_from_gains(args.ctle_dcgain_db, args.ctle_boost_db,
                                                  f_nyquist, args.ctle_fp2, args.ctle_pole1_frac)

        def response_fn(freqs):
            return compute_ac_response(ctle_tf, freqs)

        return response_fn, info, "from gains (DCgain + Boost + fp2, wp1 below Nyquist)"
    else:
        ctle_tf, info = build_ctle_tf(args.ctle_gmn, args.ctle_rl, args.ctle_cltot,
                                       args.ctle_rs, args.ctle_cs, args.ctle_gdsn)

        def response_fn(freqs):
            return compute_ac_response(ctle_tf, freqs)

        return response_fn, info, "analytic (2 poles + 1 zero, components)"


def plot_combined_ac_response(freqs: np.ndarray, curves: dict, nyquist_freq: float, outpath: str):
    """curves: dict {label: complex H(freqs)} -- plots them all together
    in dB, marking Nyquist."""
    fig, ax = plt.subplots(figsize=(9, 5.5))
    for label, H in curves.items():
        ax.plot(freqs / 1e9, 20 * np.log10(np.abs(H) + 1e-30), label=label)

    ax.axvline(nyquist_freq / 1e9, color="gray", linestyle=":", linewidth=1,
               label=f"Nyquist ({nyquist_freq/1e9:.3f} GHz)")
    ax.set_xlabel("Frequency (GHz)")
    ax.set_ylabel("|H(f)| (dB)")
    ax.set_title("Combined AC response: Channel, +FFE, +FFE+CTLE")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(outpath, dpi=150)
    plt.close()
    print(f"Saved: {outpath}")


