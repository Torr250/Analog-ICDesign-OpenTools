def channel_coefficients(pulse_response: np.ndarray, samples_per_symbol: int,
                          n_precursors: int, n_postcursors: int) -> np.ndarray:
    """Samples the pulse response at multiples of the UI around the main
    cursor (the peak). Returns n_precursors + 1 + n_postcursors
    coefficients."""
    n_cursors = n_precursors + n_postcursors + 1
    coeffs = np.zeros(n_cursors)

    max_idx = int(np.argmax(pulse_response))

    for cursor in range(n_cursors):
        a = cursor - n_precursors
        idx = max_idx + a * samples_per_symbol
        coeffs[cursor] = pulse_response[idx] if 0 <= idx < len(pulse_response) else 0.0

    return coeffs


def wc_eye_height(pulse_response: np.ndarray, samples_per_symbol: int,
                   n_precursors: int, n_postcursors: int) -> float:
    """Worst Case Eye Height by the coefficients method: it groups all the
    negative ISI coefficients (which close the '1') on one side, and the
    positive ones (which close the '0') on the other, and computes the
    resulting opening for the worst possible bit pattern. Positive = open
    eye, negative = closed eye.

    FIXED with respect to the first version: previously n_precursors+1
    coefficients were requested but only n_precursors were summed,
    unintentionally excluding the precursor closest to the main cursor from
    the count. Now ALL the n_precursors + n_postcursors coefficients are
    used and summed, with none excluded."""
    ch_coeff = channel_coefficients(pulse_response, samples_per_symbol,
                                     n_precursors, n_postcursors)

    pulse_peak = ch_coeff[n_precursors]
    WC0, WC1 = 0.0, 0.0

    for x in range(n_precursors):
        if ch_coeff[x] < 0:
            WC1 += ch_coeff[x]
        else:
            WC0 += ch_coeff[x]

    for x in range(n_postcursors):
        val = ch_coeff[n_precursors + 1 + x]
        if val < 0:
            WC1 += val
        else:
            WC0 += val

    return 2 * (pulse_peak + WC1 - WC0)


def build_worst_case_bit_pattern(pulse_response: np.ndarray, samples_per_symbol: int,
                                  n_precursors: int, n_postcursors: int):
    """
    Builds the bit sequence (bipolar, +-1) that generates EXACTLY the Worst
    Case Eye Height computed by wc_eye_height().

    IMPORTANT DETAIL (non-trivial): the contribution of the bit transmitted
    at position j to the value sampled at the main position is NOT
    ch_coeff[j] -- it is ch_coeff[2*main_idx - j] (the "mirrored"
    coefficient). This comes from superposition: r(t_main) = sum_j b[j] *
    p(t_main - T_j), and p evaluated 'backwards' from its own peak is the
    coefficient with the reflected index, not the same one. Since
    n_precursors and n_postcursors are usually different (asymmetric), in
    order to mirror without going out of range the coefficients are
    recomputed with a SYMMETRIC range (using the maximum of both on each
    side) before building the pattern -- the NUMERICAL computation of
    wc_eye_height() is not touched, this is only for the synthesis of the
    waveform.

    Returns (bit_pattern, ch_coeff, main_idx) -- bit_pattern and ch_coeff
    have the SAME length and indexing (useful to synthesize the waveform
    with synthesize_worst_case_waveform).
    """
    n_sym = max(n_precursors, n_postcursors)
    ch_coeff = channel_coefficients(pulse_response, samples_per_symbol, n_sym, n_sym)
    main_idx = n_sym

    bit_pattern = np.zeros(len(ch_coeff))
    bit_pattern[main_idx] = 1.0
    for j in range(len(ch_coeff)):
        if j == main_idx:
            continue
        mirrored_idx = 2 * main_idx - j
        coeff_val = ch_coeff[mirrored_idx]
        bit_pattern[j] = 1.0 if coeff_val < 0 else -1.0

    return bit_pattern, ch_coeff, main_idx


def synthesize_worst_case_waveform(pulse_response: np.ndarray, samples_per_symbol: int,
                                    bit_pattern: np.ndarray, main_idx: int, ui_window: float = 2.0):
    """
    Synthesizes the continuous waveform for the given bit sequence, by
    superposition of shifted and scaled copies of the pulse response (the
    channel is LTI) -- with no need for ngspice. Returns
    (grid_in_ui, waveform) cropped to +-ui_window/2 UI around the main
    cursor, in the same format used by eye_diagram.py.
    """
    n = len(pulse_response)
    n_precursors_in_array = main_idx
    n_postcursors_in_array = len(bit_pattern) - main_idx - 1

    pad_left = n_precursors_in_array * samples_per_symbol
    pad_right = n_postcursors_in_array * samples_per_symbol
    total = np.zeros(pad_left + n + pad_right)

    for k, bit in enumerate(bit_pattern):
        a = k - main_idx
        shift = pad_left + a * samples_per_symbol
        total[shift:shift + n] += bit * pulse_response

    max_idx_local = int(np.argmax(pulse_response))
    center = pad_left + max_idx_local

    half_win = int(round(ui_window / 2 * samples_per_symbol))
    lo, hi = center - half_win, center + half_win
    window = total[max(lo, 0):min(hi, len(total))]

    grid_in_ui = (np.arange(len(window)) - (center - max(lo, 0))) / samples_per_symbol
    return grid_in_ui, window


def plot_worst_case_eye(pulse_response: np.ndarray, samples_per_symbol: int,
                         n_precursors: int, n_postcursors: int, wceh: float, outpath: str,
                         overlay_npz: str = None, vdd: float = None):
    """
    If 'vdd' is passed, rescales the traces (which come out in the BIPOLAR
    +-1 convention, the same one used by the synthesis) to the UNIPOLAR
    0..VDD convention used by the real ngspice simulations (mapping:
    unipolar = VDD/2*(1+bipolar), the same transformation done by
    'sgn(V)*VDD/2+VDD/2' in the netlists) -- needed so that the overlay
    with a real eye_*.npz makes visual sense (otherwise they end up on
    different scales).
    """
    bit_pattern_1, ch_coeff, main_idx = build_worst_case_bit_pattern(
        pulse_response, samples_per_symbol, n_precursors, n_postcursors)
    bit_pattern_0 = -bit_pattern_1  # bipolar symmetry: the worst '0' is the complement of the worst '1'

    grid1, wave1 = synthesize_worst_case_waveform(pulse_response, samples_per_symbol, bit_pattern_1, main_idx)
    grid0, wave0 = synthesize_worst_case_waveform(pulse_response, samples_per_symbol, bit_pattern_0, main_idx)

    scale = 1.0
    if vdd is not None:
        wave1 = vdd / 2 * (1 + wave1)
        wave0 = vdd / 2 * (1 + wave0)
        scale = vdd / 2  # the gap/WCEH is also rescaled (without the +1 offset, which cancels out in the subtraction)

    fig, ax = plt.subplots(figsize=(10, 6))

    if overlay_npz and os.path.isfile(overlay_npz):
        data = np.load(overlay_npz, allow_pickle=True)
        grid_bg, matrix_bg = data["grid_in_ui"], data["matrix"]
        for row in matrix_bg:
            ax.plot(grid_bg, row, color="lightgray", alpha=0.25, linewidth=0.6, zorder=1)
        ax.plot([], [], color="gray", alpha=0.6, label="Real PRBS (ngspice, reference)")
        if vdd is None:
            print("Warning: overlaying on ngspice data (0..VDD) without passing --vdd -- "
                  "the scales will probably not match. Pass --vdd to rescale.")

    ax.plot(grid1, wave1, color="firebrick", linewidth=2, label="Worst case '1'", zorder=3)
    ax.plot(grid0, wave0, color="steelblue", linewidth=2, label="Worst case '0'", zorder=3)

    ax.axvline(0.0, color="green", linestyle=":", linewidth=1, alpha=0.7, label="center (sampling instant)")

    level_1 = wave1[np.argmin(np.abs(grid1))]
    level_0 = wave0[np.argmin(np.abs(grid0))]
    full_gap = level_1 - level_0
    wceh_scaled = wceh * scale
    ax.scatter([0, 0], [level_1, level_0], color="black", zorder=5)
    units = "V" if vdd is not None else "(pulse units)"
    ax.annotate(
        f"measured gap = {full_gap:.4f} {units}\n"
        f"WC eye height (formula) = {wceh_scaled:.4f} {units}",
        xy=(0, (level_1 + level_0) / 2), xytext=(15, 0), textcoords="offset points",
        fontsize=8, va="center")

    ax.set_xlabel("Time (UI, 0 = main cursor)")
    ax.set_ylabel("Amplitude (V)" if vdd is not None else "Amplitude (input pulse units)")
    ax.set_title(f"Worst-case eye (deterministic) — WC eye height = {wceh_scaled:.4f} {units}")
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(outpath, dpi=150)
    plt.close()
    print(f"Saved: {outpath}")


def plot_channel_coefficients(coeffs: np.ndarray, n_precursors: int, outpath: str):
    idx = np.arange(-n_precursors, len(coeffs) - n_precursors)
    colors = ["firebrick" if i == 0 else ("steelblue" if c >= 0 else "darkorange")
              for i, c in zip(idx, coeffs)]

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.bar(idx, coeffs, color=colors, width=0.6)
    ax.axhline(0, color="black", linewidth=0.8)
    ax.set_xlabel("Cursor (n, in UI relative to the peak)")
    ax.set_ylabel("Channel coefficient")
    ax.set_title("Channel coefficients (red = main, orange = negative ISI, blue = positive ISI)")
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(outpath, dpi=150)
    plt.close()
    print(f"Saved: {outpath}")


