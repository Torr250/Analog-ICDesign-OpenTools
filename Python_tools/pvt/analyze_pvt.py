#!/usr/bin/env python3
"""
analyze_pvt.py

Analyzes the results of pvt_results.csv (generated by pvt_runner.py /
pvt_runner_plots.py) and:
  1. Prints a worst/best-case summary per metric, grouped by type of
     physical quantity (time, current, efficiency, or whatever you define in
     MEAS_GROUPS) so that each one is displayed in its natural unit.
  2. Generates plots for each group of metrics, with no special cases by
     metric or group name:
     - Bars: worst case per process corner (only if the group contains
       more than one metric, e.g. trise/tfall/tplh/tphl together)
     - Heatmap: each individual metric, corner vs temperature, one
       for each VDD
     - Boxplot: spread of each individual metric per corner
       (across temp/vdd)

To reuse this script with another circuit: add/remove column names in
MEAS_GROUPS (below) according to the measurements your netlist has.
There is no need to touch the rest of the code.

Usage:
    python3 analyze_pvt.py [path_to_csv]

If no path is passed, it uses 'pvt_results.csv' in the current directory.
Requires: pandas, matplotlib
    pip install pandas matplotlib --break-system-packages
"""

import sys
import os
import pandas as pd
import matplotlib.pyplot as plt

# ----------------------------------------------------------------------
# Metric groups: each one has its own family of SI units,
# because it makes no sense to mix seconds with amperes on the same scale.
# ----------------------------------------------------------------------

TIME_COLS = ["trise", "tfall", "tplh", "tphl", "tpd_avg"]
CURRENT_COLS = ["ivdd_rms"]
EFFICIENCY_COLS = ["effy"]  # already in mW/GHz, not rescaled

_UNITS_TIME = [
    (1e0, "s"), (1e-3, "ms"), (1e-6, "us"), (1e-9, "ns"), (1e-12, "ps"), (1e-15, "fs"),
]
_UNITS_CURRENT = [
    (1e0, "A"), (1e-3, "mA"), (1e-6, "uA"), (1e-9, "nA"), (1e-12, "pA"),
]

# Definition of each group: columns present (filtered against the real CSV),
# unit table to use (None = do not rescale), default unit if there is no data,
# and whether a higher value is better or worse for that quantity (to know what is
# "worst case" and what is "best case" when aggregating by corner).
MEAS_GROUPS = {
    "time": {
        "cols": TIME_COLS,
        "units": _UNITS_TIME,
        "default": (1e-12, "ps"),
        "higher_is_better": False,   # shorter time = better
    },
    "current": {
        "cols": CURRENT_COLS,
        "units": _UNITS_CURRENT,
        "default": (1e-6, "uA"),
        "higher_is_better": False,   # lower current = better
    },
    "efficiency": {
        "cols": EFFICIENCY_COLS,
        "units": None,          # no rescaling: it is already in mW/GHz
        "default": (1.0, "mW/GHz"),
        "higher_is_better": False,   # lower mW/GHz = better (more efficient)
    },
}


def best_unit_for(values, units, default):
    """
    Chooses the most readable SI scale/unit for a set of values,
    using the median as the magnitude reference.
    If units is None, no rescaling is possible ('default' is used as is).
    """
    if units is None:
        return default

    clean = sorted(v for v in values if v is not None and not pd.isna(v) and v != 0)
    if not clean:
        return default

    median = clean[len(clean) // 2]
    for scale, name in units:
        if median >= scale:
            return scale, name
    return units[-1]


def fmt_val(value, scale, unit, decimals=2):
    """Formats a value already in base units (s, A, mW/GHz) to the given scale/unit."""
    if value is None or pd.isna(value):
        return "N/A"
    return f"{value / scale:.{decimals}f} {unit}"


def load_data(csv_path: str) -> pd.DataFrame:
    if not os.path.isfile(csv_path):
        print(f"Error: '{csv_path}' not found", file=sys.stderr)
        sys.exit(1)
    df = pd.read_csv(csv_path)

    present_meas = [c for c in TIME_COLS + CURRENT_COLS + EFFICIENCY_COLS if c in df.columns]
    missing_before = df[present_meas].isna().sum()
    if missing_before.sum() > 0:
        print("Warning: some measurements came back empty (possible trigger/target/param failure):")
        print(missing_before[missing_before > 0].to_string())
        print()

    if "tpd_avg" not in df.columns and "tplh" in df.columns and "tphl" in df.columns:
        # fallback for compatibility with old netlists that did not compute tpd_avg themselves
        df["tpd_avg"] = df[["tplh", "tphl"]].mean(axis=1)

    return df


def active_groups(df: pd.DataFrame):
    """Returns {group_name: {cols, scale, unit, higher_is_better}} only for
    columns present in the CSV."""
    groups = {}
    for name, cfg in MEAS_GROUPS.items():
        cols = [c for c in cfg["cols"] if c in df.columns]
        if not cols:
            continue
        all_values = df[cols].values.flatten()
        scale, unit = best_unit_for(all_values, cfg["units"], cfg["default"])
        groups[name] = {
            "cols": cols,
            "scale": scale,
            "unit": unit,
            "higher_is_better": cfg.get("higher_is_better", False),
        }
    return groups


def print_worst_case_summary(df: pd.DataFrame, groups: dict):
    corners_order = ["ff", "typical", "ss", "fs", "sf"]
    corners_order = [c for c in corners_order if c in df["corner"].unique()]
    corners_order += [c for c in df["corner"].unique() if c not in corners_order]

    for gname, g in groups.items():
        cols, scale, unit = g["cols"], g["scale"], g["unit"]
        higher_is_better = g["higher_is_better"]
        # if a higher value is better, the worst case is the minimum and vice versa
        worst_fn, best_fn = ("idxmin", "idxmax") if higher_is_better else ("idxmax", "idxmin")
        worst_agg, best_agg = ("min", "max") if higher_is_better else ("max", "min")

        print("=" * 70)
        print(f"GROUP: {gname.upper()}  (units: {unit}, "
              f"{'higher = better' if higher_is_better else 'lower = better'})")
        print("=" * 70)

        for meas in cols:
            valid = df.dropna(subset=[meas])
            if valid.empty:
                print(f"\n{meas}: no valid data")
                continue

            worst_row = valid.loc[getattr(valid[meas], worst_fn)()]
            best_row = valid.loc[getattr(valid[meas], best_fn)()]

            print(f"\n{meas}:")
            print(f"  Worst case: {fmt_val(worst_row[meas], scale, unit)}  "
                  f"(corner={worst_row['corner']}, temp={worst_row['temp']}C, vdd={worst_row['vdd']}V)")
            print(f"  Best case : {fmt_val(best_row[meas], scale, unit)}  "
                  f"(corner={best_row['corner']}, temp={best_row['temp']}C, vdd={best_row['vdd']}V)")
            if best_row[meas] != 0:
                ratio = worst_row[meas] / best_row[meas] if not higher_is_better else best_row[meas] / worst_row[meas]
                print(f"  Range (worst/best): {ratio:.2f}x")

        print(f"\n--- Worst case per process corner — {gname} ({unit}) ---")
        corner_worst_series = getattr(df.groupby("corner")[cols], worst_agg)().reindex(corners_order)
        print((corner_worst_series / scale).to_string(float_format=lambda x: f"{x:.2f}"))

        if len(cols) == 1:
            per_corner = getattr(df.groupby("corner")[cols[0]], worst_agg)()
            overall_worst_corner = per_corner.idxmin() if higher_is_better else per_corner.idxmax()
            print(f"\n>> Corner with the worst {cols[0]} overall: '{overall_worst_corner}'")
        print()


# ----------------------------------------------------------------------
# Generic plots: reused for any group of metrics
# ----------------------------------------------------------------------

def plot_bar_by_corner(df: pd.DataFrame, cols: list, scale: float, unit: str,
                        agg: str, title: str, fname: str, outdir: str):
    """Bars: aggregated value (agg='max' or 'min') of each metric of the group, per corner."""
    corner_agg = getattr(df.groupby("corner")[cols], agg)() / scale

    ax = corner_agg.plot(kind="bar", figsize=(9, 5))
    ax.set_ylabel(f"Value ({unit})")
    ax.set_xlabel("Process corner")
    ax.set_title(title)
    ax.legend(title="Metric")
    plt.xticks(rotation=0)
    plt.tight_layout()
    path = os.path.join(outdir, fname)
    plt.savefig(path, dpi=150)
    plt.close()
    print(f"Saved: {path}")


def plot_heatmap_by_vdd(df: pd.DataFrame, metric: str, scale: float, unit: str,
                         title: str, fname: str, outdir: str):
    """Heatmap of a metric (corner x temp) for each VDD value."""
    vdds = sorted(df["vdd"].unique())
    fig, axes = plt.subplots(1, len(vdds), figsize=(5 * len(vdds), 4.5), sharey=True)
    if len(vdds) == 1:
        axes = [axes]

    corners_order = ["ff", "typical", "ss", "fs", "sf"]
    corners_order = [c for c in corners_order if c in df["corner"].unique()]
    corners_order += [c for c in df["corner"].unique() if c not in corners_order]

    for ax, vdd in zip(axes, vdds):
        sub = df[df["vdd"] == vdd]
        pivot = sub.pivot_table(index="corner", columns="temp", values=metric) / scale
        pivot = pivot.reindex(corners_order)

        im = ax.imshow(pivot.values, cmap="RdYlGn_r", aspect="auto")
        ax.set_xticks(range(len(pivot.columns)))
        ax.set_xticklabels(pivot.columns)
        ax.set_yticks(range(len(pivot.index)))
        ax.set_yticklabels(pivot.index)
        ax.set_xlabel("Temp (°C)")
        ax.set_title(f"VDD = {vdd} V")

        for i in range(pivot.shape[0]):
            for j in range(pivot.shape[1]):
                val = pivot.values[i, j]
                if pd.notna(val):
                    ax.text(j, i, f"{val:.2f}", ha="center", va="center", fontsize=8)

        fig.colorbar(im, ax=ax, label=f"{metric} ({unit})", shrink=0.8)

    axes[0].set_ylabel("Process corner")
    fig.suptitle(title)
    plt.tight_layout()
    path = os.path.join(outdir, fname)
    plt.savefig(path, dpi=150)
    plt.close()
    print(f"Saved: {path}")


def plot_boxplot_by_corner(df: pd.DataFrame, metric: str, scale: float, unit: str,
                            title: str, fname: str, outdir: str):
    """Boxplot of a metric per corner, to see the spread across temp/vdd."""
    corners_order = ["ff", "typical", "ss", "fs", "sf"]
    corners_order = [c for c in corners_order if c in df["corner"].unique()]
    corners_order += [c for c in df["corner"].unique() if c not in corners_order]

    data = [(df[df["corner"] == c][metric].dropna() / scale).values for c in corners_order]

    fig, ax = plt.subplots(figsize=(8, 5))
    try:
        ax.boxplot(data, tick_labels=corners_order, showmeans=True)
    except TypeError:
        ax.boxplot(data, labels=corners_order, showmeans=True)
    ax.set_ylabel(f"{metric} ({unit})")
    ax.set_xlabel("Process corner")
    ax.set_title(title)
    plt.tight_layout()
    path = os.path.join(outdir, fname)
    plt.savefig(path, dpi=150)
    plt.close()
    print(f"Saved: {path}")


def generate_plots(df: pd.DataFrame, groups: dict, outdir: str):
    for gname, g in groups.items():
        cols, scale, unit = g["cols"], g["scale"], g["unit"]
        higher_is_better = g["higher_is_better"]
        worst_agg, best_agg = ("min", "max") if higher_is_better else ("max", "min")

        # Comparative bars: only make sense if the group contains more than one metric
        # (e.g. trise/tfall/tplh/tphl together); a single-metric group does not need a bar chart.
        if len(cols) > 1:
            plot_bar_by_corner(
                df, cols, scale, unit, agg=worst_agg,
                title=f"Worst case per metric of group '{gname}' and corner (all temp/VDD)",
                fname=f"worst_by_corner_{gname}.png", outdir=outdir,
            )
            plot_bar_by_corner(
                df, cols, scale, unit, agg=best_agg,
                title=f"Best case per metric of group '{gname}' and corner (all temp/VDD)",
                fname=f"best_by_corner_{gname}.png", outdir=outdir,
            )

        # Individual heatmap + boxplot for EVERY metric of the group (no exceptions)
        for metric in cols:
            plot_heatmap_by_vdd(
                df, metric, scale, unit,
                title=f"{metric} by corner and temperature, per VDD — in {unit}",
                fname=f"heatmap_{metric}_by_vdd.png", outdir=outdir,
            )
            plot_boxplot_by_corner(
                df, metric, scale, unit,
                title=f"Spread of {metric} per corner (across temp x VDD)",
                fname=f"boxplot_{metric}_by_corner.png", outdir=outdir,
            )


def main():
    csv_path = sys.argv[1] if len(sys.argv) > 1 else "pvt_results.csv"
    outdir = "pvt_analysis"
    os.makedirs(outdir, exist_ok=True)

    df = load_data(csv_path)
    groups = active_groups(df)

    print("Metric groups detected in the CSV:")
    for gname, g in groups.items():
        print(f"  - {gname}: {g['cols']}  (unit: {g['unit']})")
    print()

    print_worst_case_summary(df, groups)

    print("Generating plots...")
    generate_plots(df, groups, outdir)

    # full numeric summary (all the columns, in base units without rescaling),
    # respecting the higher_is_better criterion of each group separately
    worst_parts, best_parts = [], []
    for g in groups.values():
        cols = g["cols"]
        worst_agg, best_agg = ("min", "max") if g["higher_is_better"] else ("max", "min")
        worst_parts.append(getattr(df.groupby("corner")[cols], worst_agg)())
        best_parts.append(getattr(df.groupby("corner")[cols], best_agg)())

    worst_summary_path = os.path.join(outdir, "worst_case_summary.csv")
    pd.concat(worst_parts, axis=1).to_csv(worst_summary_path)
    print(f"\nNumeric worst-case summary (base units) saved to: {worst_summary_path}")

    best_summary_path = os.path.join(outdir, "best_case_summary.csv")
    pd.concat(best_parts, axis=1).to_csv(best_summary_path)
    print(f"Numeric best-case summary (base units) saved to: {best_summary_path}")

    print(f"Plots saved to: {outdir}/")


if __name__ == "__main__":
    main()
