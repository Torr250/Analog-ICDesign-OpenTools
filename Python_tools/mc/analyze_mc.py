#!/usr/bin/env python3
"""
analyze_mc.py

Analyzes the results of mc_results.csv (generated by mc_runner.py) and:
  1. Prints statistics per metric: mean, sigma, min, max, median,
     coefficient of variation (%), and ±3sigma range.
  2. If a spec is passed (--spec) for a metric, computes its YIELD
     (% of runs that meet the limit) and marks the limit on the
     histogram. Metrics WITHOUT a spec are still reported the same way as
     before (mean/sigma/histogram), simply without yield.
  3. Generates one histogram per metric.
  4. Saves a numeric summary in mc_summary.csv (yield_pct is left empty
     for the metrics without a spec).

Uses the same group/unit scheme as analyze_pvt.py (time, current,
efficiency) so that the units are displayed in a readable way
(ps, uA, mW/GHz) instead of scientific notation.

Usage:
    python3 analyze_mc.py [path_to_csv]
    python3 analyze_mc.py mc_results.csv --spec tpd_avg:lt:1.3e-10
    python3 analyze_mc.py --spec tpd_avg:lt:1.3e-10 --spec ivdd_rms:lt:2.5e-4

Format of --spec (repeatable, one per limit):
    metric:op:value
    where op is one of: lt (<), le (<=), gt (>), ge (>=)
    and value is in BASE UNITS (seconds, amperes, mW/GHz) — not in ps/uA.

    A metric with both an upper AND a lower limit needs two --spec:
        --spec tpd_avg:gt:9e-11 --spec tpd_avg:lt:1.3e-10

If no --spec is passed, the script works exactly as it did
before (without yield). Metrics that do not appear in any --spec have
no yield, so only a subset can be specified.

Requires: pandas, matplotlib
    pip install pandas matplotlib --break-system-packages
"""

import argparse
import sys
import os
import pandas as pd
import matplotlib.pyplot as plt

# ----------------------------------------------------------------------
# Same group/unit scheme as analyze_pvt.py
# ----------------------------------------------------------------------

TIME_COLS = ["trise", "tfall", "tplh", "tphl", "tpd_avg"]
CURRENT_COLS = ["ivdd_rms"]
EFFICIENCY_COLS = ["effy"]  # already in mW/GHz, not rescaled

_UNITS_TIME = [
    (1e0, "s"), (1e-3, "ms"), (1e-6, "us"), (1e-9, "ns"), (1e-12, "ps"), (1e-15, "fs"),
]
_UNITS_CURRENT = [
    (1e0, "A"), (1e-3, "mA"), (1e-6, "uA"), (1e-9, "nA"), (1e-12, "pA"),
]

MEAS_GROUPS = {
    "time": {
        "cols": TIME_COLS,
        "units": _UNITS_TIME,
        "default": (1e-12, "ps"),
    },
    "current": {
        "cols": CURRENT_COLS,
        "units": _UNITS_CURRENT,
        "default": (1e-6, "uA"),
    },
    "efficiency": {
        "cols": EFFICIENCY_COLS,
        "units": None,
        "default": (1.0, "mW/GHz"),
    },
}

_OPS = {
    "lt": (lambda s, v: s < v, "<"),
    "le": (lambda s, v: s <= v, "<="),
    "gt": (lambda s, v: s > v, ">"),
    "ge": (lambda s, v: s >= v, ">="),
}


def best_unit_for(values, units, default):
    if units is None:
        return default
    clean = sorted(v for v in values if v is not None and not pd.isna(v) and v != 0)
    if not clean:
        return default
    median = clean[len(clean) // 2]
    for scale, name in units:
        if median >= scale:
            return scale, name
    return units[-1]


def fmt_val(value, scale, unit, decimals=3):
    if value is None or pd.isna(value):
        return "N/A"
    return f"{value / scale:.{decimals}f} {unit}"


def parse_specs(spec_args):
    """
    Converts a list of 'metric:op:value' strings into a dict:
        {metric: [(op_fn, op_label, value), ...]}
    Several entries for the same metric accumulate (e.g. a lower
    AND an upper limit at the same time).
    """
    specs = {}
    for raw in spec_args or []:
        parts = raw.split(":")
        if len(parts) != 3:
            print(f"Error: invalid spec '{raw}', expected format metric:op:value", file=sys.stderr)
            sys.exit(1)
        metric, op, value_str = parts
        if op not in _OPS:
            print(f"Error: invalid operator '{op}' in '{raw}'. Use: {list(_OPS)}", file=sys.stderr)
            sys.exit(1)
        try:
            value = float(value_str)
        except ValueError:
            print(f"Error: invalid value '{value_str}' in '{raw}'", file=sys.stderr)
            sys.exit(1)
        op_fn, op_label = _OPS[op]
        specs.setdefault(metric, []).append((op_fn, op_label, value))
    return specs


def load_data(csv_path: str) -> pd.DataFrame:
    if not os.path.isfile(csv_path):
        print(f"Error: '{csv_path}' not found", file=sys.stderr)
        sys.exit(1)
    df = pd.read_csv(csv_path)

    present_meas = [c for c in TIME_COLS + CURRENT_COLS + EFFICIENCY_COLS if c in df.columns]
    missing = df[present_meas].isna().sum()
    if missing.sum() > 0:
        print("Warning: some runs have empty measurements (possible trigger/target failure):")
        print(missing[missing > 0].to_string())
        print()

    if "tpd_avg" not in df.columns and "tplh" in df.columns and "tphl" in df.columns:
        df["tpd_avg"] = df[["tplh", "tphl"]].mean(axis=1)

    return df


def active_groups(df: pd.DataFrame):
    groups = {}
    for name, cfg in MEAS_GROUPS.items():
        cols = [c for c in cfg["cols"] if c in df.columns]
        if not cols:
            continue
        all_values = df[cols].values.flatten()
        scale, unit = best_unit_for(all_values, cfg["units"], cfg["default"])
        groups[name] = {"cols": cols, "scale": scale, "unit": unit}
    return groups


def compute_stats(series: pd.Series) -> dict:
    valid = series.dropna()
    n = len(valid)
    mean = valid.mean() if n else float("nan")
    std = valid.std(ddof=1) if n > 1 else float("nan")
    return {
        "n": n,
        "mean": mean,
        "std": std,
        "min": valid.min() if n else float("nan"),
        "max": valid.max() if n else float("nan"),
        "median": valid.median() if n else float("nan"),
        "cv_pct": (std / mean * 100.0) if mean else float("nan"),
        "min3sigma": mean - 3 * std if n > 1 else float("nan"),
        "max3sigma": mean + 3 * std if n > 1 else float("nan"),
    }


def compute_yield(series: pd.Series, constraints: list):
    """
    constraints: [(op_fn, op_label, value), ...] already combined with AND.
    Returns (yield_pct, n_fail, mask) or (None, None, None) if there are no constraints.
    """
    if not constraints:
        return None, None, None
    valid = series.dropna()
    mask = pd.Series(True, index=valid.index)
    for op_fn, _, value in constraints:
        mask &= op_fn(valid, value)
    yield_pct = mask.mean() * 100.0
    n_fail = (~mask).sum()
    return yield_pct, n_fail, mask


def spec_desc(constraints: list, scale: float, unit: str) -> str:
    parts = [f"{op_label} {value / scale:.3f} {unit}" for _, op_label, value in constraints]
    return " and ".join(parts)


def spec_desc_base(constraints: list, unit: str) -> str:
    """Same as spec_desc but for the CSV, in base units (uses scientific
    notation so that small values such as 1.1e-10 are not truncated to '0.000')."""
    parts = [f"{op_label} {value:.4e} {unit}" for _, op_label, value in constraints]
    return " and ".join(parts)


def print_summary(df: pd.DataFrame, groups: dict, specs: dict):
    for gname, g in groups.items():
        cols, scale, unit = g["cols"], g["scale"], g["unit"]

        print("=" * 70)
        print(f"GROUP: {gname.upper()}  (units: {unit})")
        print("=" * 70)

        for metric in cols:
            s = compute_stats(df[metric])
            print(f"\n{metric}  (n={s['n']}):")
            print(f"  Mean     : {fmt_val(s['mean'], scale, unit)}")
            print(f"  Sigma    : {fmt_val(s['std'], scale, unit)}   (CV = {s['cv_pct']:.2f}%)")
            print(f"  Median   : {fmt_val(s['median'], scale, unit)}")
            print(f"  Min/Max  : {fmt_val(s['min'], scale, unit)} / {fmt_val(s['max'], scale, unit)}")
            print(f"  ±3sigma range: [{fmt_val(s['min3sigma'], scale, unit)}, {fmt_val(s['max3sigma'], scale, unit)}]")

            constraints = specs.get(metric)
            if constraints:
                yield_pct, n_fail, _ = compute_yield(df[metric], constraints)
                desc = spec_desc(constraints, scale, unit)
                print(f"  Spec     : {desc}")
                print(f"  Yield    : {yield_pct:.2f}%   ({n_fail} of {s['n']} runs out of spec)")
            else:
                print(f"  Spec     : (not defined — yield is not computed for this metric)")
        print()

    # combined yield: all the metrics with a spec must be met at the same time
    specced_metrics = [m for m in specs if m in df.columns]
    if len(specced_metrics) > 1:
        combined_mask = pd.Series(True, index=df.index)
        for metric in specced_metrics:
            valid_mask = df[metric].notna()
            combined_mask &= valid_mask
            for op_fn, _, value in specs[metric]:
                combined_mask &= op_fn(df[metric], value).reindex(df.index, fill_value=False)
        combined_yield = combined_mask.mean() * 100.0
        print("=" * 70)
        print(f"COMBINED YIELD ({' + '.join(specced_metrics)}): {combined_yield:.2f}% "
              f"({(~combined_mask).sum()} of {len(df)} runs fail at least one spec)")
        print("=" * 70)
        print()


def plot_histogram(df: pd.DataFrame, metric: str, scale: float, unit: str, outdir: str, constraints: list):
    s = compute_stats(df[metric])
    values = (df[metric].dropna() / scale)
    mean = s["mean"] / scale
    std = s["std"] / scale if pd.notna(s["std"]) else 0

    fig, ax = plt.subplots(figsize=(8, 5))
    n_bins = max(5, min(30, len(values) // 2 or 5))
    ax.hist(values, bins=n_bins, color="steelblue", edgecolor="white", alpha=0.85)

    ax.axvline(mean, color="black", linestyle="-", linewidth=1.5, label=f"mean = {mean:.3f} {unit}")
    if std > 0:
        ax.axvline(mean - 3 * std, color="red", linestyle="--", linewidth=1, label="±3σ")
        ax.axvline(mean + 3 * std, color="red", linestyle="--", linewidth=1)

    title_extra = ""
    if constraints:
        yield_pct, _, _ = compute_yield(df[metric], constraints)
        for _, op_label, value in constraints:
            ax.axvline(value / scale, color="darkorange", linestyle=":", linewidth=2,
                       label=f"spec {op_label} {value/scale:.3f} {unit}")
        title_extra = f", yield={yield_pct:.1f}%"

    ax.set_xlabel(f"{metric} ({unit})")
    ax.set_ylabel("Count (# runs)")
    ax.set_title(f"Monte Carlo distribution — {metric}  (n={s['n']}, CV={s['cv_pct']:.2f}%{title_extra})")
    ax.legend(fontsize=8)
    plt.tight_layout()

    fname = os.path.join(outdir, f"hist_{metric}.png")
    plt.savefig(fname, dpi=150)
    plt.close()
    print(f"Saved: {fname}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("csv_path", nargs="?", default="mc_results.csv", help="Path to the MC results CSV")
    parser.add_argument("--spec", action="append", default=[],
                         help="Spec limit: metric:op:value (repeatable). op in {lt,le,gt,ge}. "
                              "Value in base units (s, A, mW/GHz).")
    args = parser.parse_args()

    outdir = "mc_analysis"
    os.makedirs(outdir, exist_ok=True)

    specs = parse_specs(args.spec)

    df = load_data(args.csv_path)
    groups = active_groups(df)

    unknown_specs = [m for m in specs if not any(m in g["cols"] for g in groups.values())]
    if unknown_specs:
        print(f"Warning: --spec for metrics not present in the CSV (ignored): {unknown_specs}\n")

    print("Metric groups detected in the CSV:")
    for gname, g in groups.items():
        specced = [c for c in g["cols"] if c in specs]
        note = f"  (with spec: {specced})" if specced else ""
        print(f"  - {gname}: {g['cols']}  (unit: {g['unit']}){note}")
    print()

    print_summary(df, groups, specs)

    print("Generating histograms...")
    all_stats_rows = []
    for gname, g in groups.items():
        for metric in g["cols"]:
            constraints = specs.get(metric)
            plot_histogram(df, metric, g["scale"], g["unit"], outdir, constraints)
            s = compute_stats(df[metric])
            s["metric"] = metric
            s["unit_base"] = "s" if gname == "time" else ("A" if gname == "current" else "mW/GHz")
            if constraints:
                yield_pct, n_fail, _ = compute_yield(df[metric], constraints)
                s["yield_pct"] = yield_pct
                s["spec"] = spec_desc_base(constraints, s["unit_base"])
            else:
                s["yield_pct"] = float("nan")
                s["spec"] = ""
            all_stats_rows.append(s)

    summary_df = pd.DataFrame(all_stats_rows).set_index("metric")
    summary_df = summary_df[["n", "mean", "std", "median", "min", "max", "cv_pct",
                              "min3sigma", "max3sigma", "yield_pct", "spec", "unit_base"]]
    summary_path = os.path.join(outdir, "mc_summary.csv")
    summary_df.to_csv(summary_path)
    print(f"\nNumeric summary (base units) saved to: {summary_path}")
    print(f"Histograms saved to: {outdir}/")


if __name__ == "__main__":
    main()
